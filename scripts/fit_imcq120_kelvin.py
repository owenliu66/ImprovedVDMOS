# ---------------------------------------------------------------------------


def main() -> None:
    OUT.mkdir(exist_ok=True)
    data = JF.JointData(include=ALL_GROUPS)
    counts = {g: int((data.group == g).sum()) for g in ALL_GROUPS}
    print(f"joint data: {len(data.v_ds)} pts {counts}, "
          f"{len(data.temps)} distinct temperatures (imported machinery, "
          f"kelvin-patched params_at)")

    start = {n: float(getattr(IMCQ120_JOINT, n)) for n in REC_FIELDS}
    start.update({"ea_bkt": 250.0, "gamma_rd": 3.3,
                  "_rd_T": data.rd_T, "_rd_vg": data.rd_vg,
                  "_rd_chord": data.rd_chord})

    results = {}
    for name in ("control", "kelvin_ideal", "degenerated", "split_free"):
        print(f"\n########## variant {name} ##########")
        st = {**start, **VARIANT_START[name]}
        r = JF.fit_variant(name, st, seeds=SEEDS[name])
        results[name] = r
        JF.report_variant(r)

        acc = JF.acceptance(r["base"], "quad", "lin")
        gap = gap_report(r["base"], r)
        print(f"   g_fs term {acc['g_fs_S']:.1f} S (spec 122, "
              f"{(acc['g_fs_S'] - 122) / 122 * 100:+.1f} %)  "
              f"intrinsic g_m {gap['g_m_intrinsic_S']:.1f} S")
        print(f"   corner v_gs=18 @20 V: 25C {acc['corner_18V']['25C']:.0f} A "
              f"(data ~3213, {gap['corner25_i18_A'] / 3213 * 100 - 100:+.1f}%)  "
              f"175C {acc['corner_18V']['175C']:.0f} A (data ~2070)  "
              f"200C {acc['corner_18V']['200C']:.0f} A")
        print(f"   25C transfer v_gs>=15 residuals: mean "
              f"{gap['corner25_res_mean_pct']:+.2f} %  range "
              f"[{gap['corner25_res_min_pct']:+.2f}, {gap['corner25_res_max_pct']:+.2f}] %")
        print(f"   Rds(on) RMSE {acc['rdson_rmse']:.2f}% max {acc['rdson_max']:.2f}% "
              f"cold {acc['rdson_cold_rmse']:.2f}%")
        print(f"   Ron chords 25C {acc['ron_25_vg18'] * 1e3:.3f}/"
              f"{acc['ron_25_vg15'] * 1e3:.3f} mOhm (data 3.70/4.70)  "
              f"175C {acc['ron_175_vg18'] * 1e3:.3f}/{acc['ron_175_vg15'] * 1e3:.3f} "
              f"(data 8.90/9.43)")
        if acc["ztc_25_175"]:
            print(f"   ZTC 25/175: {acc['ztc_25_175'][0]:.2f} V / "
                  f"{acc['ztc_25_175'][1]:.0f} A")
        print(f"   split: r_d25 {base_r(r, 'r_d25'):.4f} mOhm  "
              f"r_s25 {gap['r_tot25_mohm'] - base_r(r, 'r_d25'):.4f} mOhm  "
              f"r_sk {gap['r_sk_mohm']:.4f} mOhm  "
              f"gate degeneration r_g = r_s - r_sk = {gap['r_g_mohm']:.4f} mOhm  "
              f"r_tot25 {gap['r_tot25_mohm']:.4f} mOhm")
        if name == "control":
            drift = {n: abs(r["base"][n] - getattr(IMCQ120_JOINT, n))
                     / max(abs(getattr(IMCQ120_JOINT, n)), 1e-12)
                     for n in REC_FIELDS
                     if not np.isinf(r["sigma_rel"].get(n, 0.0))}
            dmax = max(drift.values())
            print(f"   record drift (sensed): max rel {dmax:.2e} on "
                  f"{max(drift, key=drift.get)}  "
                  f"[{'OK' if dmax < 1e-3 else 'STALE'}]")

    # comparison table
    print("\n########## comparison ##########")
    print(f"{'variant':<13} {'RMSE%':>6} {'IV%':>6} {'trf%':>6} {'rdson%':>7} "
          f"{'g_fs':>7} {'g_fs_err%':>9} {'c25A':>6} {'c25err%':>8} "
          f"{'c175A':>6} {'r_g mO':>7} {'r_tot mO':>9}")
    for name, r in results.items():
        acc = JF.acceptance(r["base"], "quad", "lin")
        gap = gap_report(r["base"], r)
        g = r["rmse_group"]
        print(f"{name:<13} {r['rmse_overall']:6.2f} {g.get('iv', 0):6.2f} "
              f"{g.get('transfer', 0):6.2f} {g.get('rdson', 0):7.2f} "
              f"{acc['g_fs_S']:7.1f} {(acc['g_fs_S'] - 122) / 122 * 100:+9.1f} "
              f"{gap['corner25_i18_A']:6.0f} "
              f"{gap['corner25_i18_A'] / 3213 * 100 - 100:+8.1f} "
              f"{acc['corner_18V']['175C']:6.0f} {gap['r_g_mohm']:7.3f} "
              f"{gap['r_tot25_mohm']:9.3f}")

    plot_transfer_25C(results)

    def ser(r: dict) -> dict:
        b = {k: v for k, v in r["base"].items() if not k.startswith("_")}
        return {"base_25C_and_TC": b, "free": list(r["free"]),
                "rmse_overall_pct": r["rmse_overall"],
                "rmse_group_pct": r["rmse_group"],
                "sigma_rel": r["sigma_rel"], "pinned": r["pinned"],
                "corr_pairs": r["corr_pairs"],
                "gap": gap_report(r["base"], r)}

    payload = {k: ser(r) for k, r in results.items()}
    (OUT / "imcq120_kelvin_params.json").write_text(
        json.dumps(payload, indent=2, default=float), encoding="utf-8")
    print("wrote", OUT / "imcq120_kelvin_params.json")


def base_r(r: dict, name: str) -> float:
    return r["base"][name] * 1e3


if __name__ == "__main__":
    main()
