OUT = ROOT / "out"
I_TEST = JF.I_TEST

# ---------------------------------------------------------------------------
# kelvin-aware params_at: same TC laws as the primary joint variant, plus
# r_s (T-flat package metal) and r_sk = f_sk * r_s (fraction of the source
# path below the kelvin tap). Patched into the joint module so JointData,
# acceptance and model_ron all evaluate the split.
# ---------------------------------------------------------------------------


def kelvin_params_at(base: dict, t_c: float, rd_law: str, bkt_law: str) -> Params:
    p = JF._base_params_at(base, t_c, rd_law, bkt_law)  # pre-patch primary
    r_s = float(base.get("r_s25", 0.0))
    r_sk = float(base.get("f_sk", 0.0)) * r_s
    return p.replace(r_s=r_s, r_sk=r_sk)


# keep the primary implementation for the TC laws (quad r_d, linear bkt)
JF._base_params_at = JF.params_at
JF.params_at = kelvin_params_at

# extend the script-local bounds table (log?, lo, hi) and variant registry
JF.FREE_SPEC["r_s25"] = (False, 0.0, 3.7e-3)   # <= datasheet 25 C chord
JF.FREE_SPEC["f_sk"] = (False, 0.0, 1.0)       # r_sk = f_sk * r_s

ALL_GROUPS = ("iv", "transfer", "rdson", "vth")
JF.VARIANTS.update({
    "control": {"free": JF.PRIMARY_FREE, "rd_law": "quad", "bkt_law": "lin",
                "groups": ALL_GROUPS},
    "kelvin_ideal": {"free": JF.PRIMARY_FREE + ("r_s25",),
                     "rd_law": "quad", "bkt_law": "lin", "groups": ALL_GROUPS},
    "degenerated": {"free": JF.PRIMARY_FREE + ("r_s25",),
                    "rd_law": "quad", "bkt_law": "lin", "groups": ALL_GROUPS},
    "split_free": {"free": JF.PRIMARY_FREE + ("r_s25", "f_sk"),
                   "rd_law": "quad", "bkt_law": "lin", "groups": ALL_GROUPS},
})

REC_FIELDS = ("k_p25", "beta_p", "v_th0_25", "s_vth", "v_sub", "k_bt25",
              "s_bkt", "k_theta", "k_ksh", "k_eta", "v_dbsat", "k_lambda",
              "r_d25", "a_rd", "b_rd")

# multi-start seeds per variant (channel knobs from the record; only the
# split knobs and, for degenerated, a stronger-channel start vary)
SEEDS = {
    "control": [],
    "kelvin_ideal": [{"r_s25": 0.2e-3}, {"r_s25": 1.0e-3}],
    "degenerated": [{"r_s25": 0.2e-3},
                    {"r_s25": 0.9e-3, "k_p25": 1.4 * IMCQ120_JOINT.k_p25,
                     "k_bt25": 0.8 * IMCQ120_JOINT.k_bt25}],
    "split_free": [{"r_s25": 0.4e-3, "f_sk": 0.0},
                   {"r_s25": 1.5e-3, "f_sk": 0.7}],
}
VARIANT_START = {
    "control": {"r_s25": 0.0, "f_sk": 0.0},
    "kelvin_ideal": {"r_s25": 0.5e-3, "f_sk": 1.0},
    "degenerated": {"r_s25": 0.5e-3, "f_sk": 0.0},
    "split_free": {"r_s25": 0.8e-3, "f_sk": 0.4},
}


# ---------------------------------------------------------------------------
# gap-closure extras (the two open gaps + the intrinsic-vs-terminal g_m story)
# ---------------------------------------------------------------------------


def gap_report(base: dict, r: dict) -> dict:
    """Quantify the two open gaps for one variant + the split quantities."""
    p25 = kelvin_params_at(base, 25.0, "quad", "lin")
    p175 = kelvin_params_at(base, 175.0, "quad", "lin")

    # 25 C transfer corner residuals (v_gs >= 15) straight off the fit vector
    data = r["data"]
    m = ((data.group == "transfer") & np.isclose(data.t_c, 25.0)
         & (data.v_gs >= 15.0))
    corner_res = r["residuals"][m]

    # terminal g_fs at 185.2 A / 20 V (as in acceptance) and the INTRINSIC
    # channel g_m at the same operating point (gate-loop degeneration
    # separates them: g_fs_term = g_m_int / (1 + r_g*g_m_int) approx)
    from scipy.optimize import brentq

    vg = brentq(lambda g: float(vdmos_id(20.0, g, p25)) - I_TEST, 5.0, 18.0)
    h = 0.01
    gfs_term = (float(vdmos_id(20.0, vg + h, p25))
                - float(vdmos_id(20.0, vg - h, p25))) / (2 * h)
    i_d = I_TEST
    r_tot = p25.r_d + p25.r_s
    r_g = p25.r_s - p25.r_sk
    vd_int, vg_int = 20.0 - r_tot * i_d, vg - r_g * i_d
    g_m_int = (float(_channel_current(vd_int, vg_int + h, p25))
               - float(_channel_current(vd_int, vg_int - h, p25))) / (2 * h)

    return {
        "corner25_res_mean_pct": float(np.mean(corner_res) * 100),
        "corner25_res_min_pct": float(np.min(corner_res) * 100),
        "corner25_res_max_pct": float(np.max(corner_res) * 100),
        "corner25_i18_A": float(vdmos_id(20.0, 18.0, p25)),
        "corner175_i18_A": float(vdmos_id(20.0, 18.0, p175)),
        "g_fs_terminal_S": gfs_term,
        "g_m_intrinsic_S": g_m_int,
        "r_tot25_mohm": (base["r_d25"] + base.get("r_s25", 0.0)) * 1e3,
        "r_g_mohm": base.get("r_s25", 0.0) * (1.0 - base.get("f_sk", 0.0)) * 1e3,
        "r_sk_mohm": base.get("f_sk", 0.0) * base.get("r_s25", 0.0) * 1e3,
    }


def plot_transfer_25C(results: dict) -> None:
    """25 C transfer: digitized data + every variant's model curve, linear +
    log -- the corner deficit and its closure, visually."""
    data = results["control"]["data"]
    m = (data.group == "transfer") & np.isclose(data.t_c, 25.0)
    fig, axes = plt.subplots(1, 2, figsize=(13, 5.4))
    axes[0].plot(data.v_gs[m], data.i_ref[m], "ko", ms=6, label="data 25 C")
    axes[1].plot(data.v_gs[m], data.i_ref[m], "ko", ms=6, label="data 25 C")
    for name, r in results.items():
        p = kelvin_params_at(r["base"], 25.0, "quad", "lin")
        r_g_mohm = r["base"].get("r_s25", 0.0) * (1 - r["base"].get("f_sk", 0.0)) * 1e3
        vgs = np.linspace(6.5, 20.0, 200)
        for ax in axes:
            ax.plot(vgs, vdmos_id(20.0, vgs, p), "--",
                    label=f"{name} (r_g {r_g_mohm:.2f} m$\\Omega$)")
    for ax, ttl in zip(axes, ["Transfer 25 C @ V_DS = 20 V: kelvin-split variants",
                              "same, log scale"], strict=True):
        ax.set_xlabel("v_gs [V]")
        ax.set_ylabel("i_d [A]")
        ax.set_title(ttl)
        ax.grid(alpha=0.3)
        ax.legend(fontsize=8)
    axes[1].set_yscale("log")
    fig.savefig(OUT / "imcq120_kelvin_transfer.png", dpi=110, bbox_inches="tight")
    plt.close(fig)
    print("wrote", OUT / "imcq120_kelvin_transfer.png")


