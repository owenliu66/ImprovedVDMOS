"""Kelvin-aware r_s split experiment for the IMCQ120R004M2H (session 22).

HANDOVER queue item 2: "r_s inside the current path but OUTSIDE the gate
loop". The session-21 joint record (reference.py::IMCQ120_JOINT, 1.93 %) has
exactly two open quantitative gaps, both blamed on the unmodeled source-side
power path (report section 8.9):

  * g_fs 129.5 S vs the 122 S spec (+6.2 %),
  * the 25 C transfer corner -5..-7 % at v_gs 15-19.2 (r_d25 = 2.40 mOhm
    drops 7.2 V at 3 kA).

This script refits the SAME 200-point joint residual vector (imported from
fit_imcq120_joint.py -- identical data, TC laws, residual definition and
acceptance checks) with the package-R split the model now supports
(model.py, r_sk; names.xlsx "sk"):

    v_ds' = v_ds - (r_d + r_s)*i_d        current loop: ALL of i_d
    v_gs' = v_gs - (r_s - r_sk)*i_d       gate loop: returns at the KELVIN tap

Variants (all start from the official record optimum; channel knobs free as
in the primary joint fit -- the split re-weights the channel, so the whole
15-param base must re-adjust):

  control       r_s = r_sk = 0            -- record reproduction sanity
                (expect 1.93 %, g_fs 129.5, corner 25C 2990 A)
  kelvin_ideal  r_sk = r_s (gate loop CLEAN, r_s fully in the current path):
                DC-DEGENERATE with control by construction (only r_d + r_s is
                sensed when the gate loop is clean) -- the quantitative proof
                that the current-loop split alone cannot close the gaps.
  degenerated   r_sk = 0 (gate loop degenerated by the full r_s): the
                "datasheet static measurement did NOT use the kelvin pin"
                hypothesis. Adds one real DC degree of freedom: the gate-loop
                degeneration r_g = r_s. Prediction: r_g ~ 0.5 mOhm explains
                g_fs (129.5/(1+129.5*r_g) ~ 122), the channel re-adjusts
                stronger, the 25 C corner deficit closes.
  split_free    r_s and f_sk = r_sk/r_s both free (0 <= f_sk <= 1): the data
                should sense r_g = r_s*(1 - f_sk) and r_d + r_s, but NOT the
                r_s/f_sk split (kelvin pin carries no DC current) -- expect
                sigma(f_sk) = inf / corr(r_s, r_sk) ~ +1.

r_s is T-FLAT (package metal: bond wires/leadframe; the Ron TC stays in the
quadratic r_d(T) law -- the chord data pins the TOTAL(T) either way, so a
free r_s TC would be unidentifiable against a_rd; not fitted).

    python scripts/fit_imcq120_kelvin.py

Long-running: launch detached and poll (120 s tool wall), e.g.
    subprocess.Popen([sys.executable, script], stdout=log, stderr=log,
                     creationflags=DETACHED_PROCESS)
"""

