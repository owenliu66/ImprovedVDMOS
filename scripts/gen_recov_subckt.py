"""Regenerate out/<part>_recov.subckt in the transit-time POLE gauge
(sessions 25a-25c) from the reference.py recovery record.

Doctrine: the subckt is GENERATED -- edit the record (or rerun
vdmos_fit.extract_recov.extract()) and rerun this script; never hand-edit
the subckt. Do NOT mix gauges: the pre-25b q_0/tau netlist form (C1=q_0/tau,
Roff=tau, B1=-I(R2)/tau) is superseded by the pole gauge (C1={t_minor},
Roff=1, E1+R3+C3 pole, B1=-I(R2)).

    python scripts/gen_recov_subckt.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from vdmos_fit import ISC040_RECOV, RecovRecord  # noqa: E402

HEADER = """* {part} — ImprovedVDMOS channel + minority-carrier body-diode recovery
* (DiodeRecov, TRANSIT-TIME POLE gauge, sessions 25a-25c).
* GENERATED by scripts/gen_recov_subckt.py from the reference.py record
* {rec_name} — edit the record (or rerun extract_recov.extract()), never
* hand-edit this file.
*
* SOLVER REQUIREMENTS (verified, LTspice 26.1.1):
*   .options method=gear reltol=1e-4 solver=alt   ; trapezoidal rings on
*                                                  ; the snap
*   B3 carries a +1u Ohm floor and R2 = 1u: in a bridge, B3
*   (transimpedance voltage source) + R1/R2 + switch Ron form near-
*   singular loops; the uOhm floor breaks them (< 0.1 % waveform impact).
*   C2 (measured C_ds charge-master, data/{cds_file}) MUST sit at Ki-A
*   INSIDE the recovery branch: at D-S terminals hard forward re-turn-on
*   crashes (D1 has no Cjo), at Ki-Ai the network is singular. Ki-A is
*   electrically D-S (B3 is a voltage source; R1 + R2 -> fc ~ 3 GHz), so
*   the caps delta stays complete. The caps delta therefore exports
*   Cgs/Cgd ONLY (ltspice.py cgs_cgd_only=True) -- Cds here, never both
*   (double-counts C_oss).
*
* FITTED RECOVERY PARAMETERS ({rec_name}; intrinsic doctrine: fit
* q_rri/t_rri on I(x1:R2) -- datasheet Qrr excludes Q_oss; t_rr = 10 % of
* I_RM; V_R = {v_r} V, I_F = {i_f} A, 25 C):
*   tau = {tau}  t_minor = {tminor}  t_pole = {tpole}
*   q_0 gauge DELETED (pure gauge) -- do NOT mix with the pre-25b form.
{points}
*   RMS {rms} % over all four datasheet numbers (pole-free two-knob: 17.45 %).
*   tau is a FLAT valley coupled to both other knobs (interior optimum
*   ~3e-4; delay law d(Delta t)/d ln tau = -t_pole): quote the coupled
*   set + RMS, never tau alone. t_pole is sharply identified.
*   Bench/extraction: src/vdmos_fit/extract_recov.py; report
*   out/recov_extract_isc040_run/extract_report.txt; doctrine
*   out/RECOV_POLE_FIT.md + out/RECOV_INTRINSIC_FIT.md.
*
"""

DEVICE = """.subckt {part} G D S
* ---- intrinsic channel (model.py expression; ISC040 channel record
*      pending -- no official channel fit exists for this part yet) ----
* Bch dx sx I=<vdmos_id(V(dx,sx), V(gx,sx))>   ; generate from model.py when the
*                                               ; ISC040 channel record exists
* For now the channel is left to the user's existing export step.
* ---- package resistance (channel path only; diode bypasses, like diode.py) ----
* Rd  D  dx  {{r_d}}
* Rs  sx s  {{r_s}}
* Rsk sx sk {{r_sk}}                       ; kelvin tap (gate loop returns at sk)
* ---- capacitance delta: Cgs/Cgd at terminals (Cds lives in the net below) ----
* Xcaps G D S {sub}           ; exported with cgs_cgd_only=True
* ---- body diode + recovery: anode = source, cathode = drain, at terminals ----
Xrec s d DiodeRecov params: Is={is_d} Rs={rs_d} N={n_d} tau={tau} \
t_minor={tminor} t_pole={tpole} k_chg={k_chg} r_max={r_max}
.ends {part}

* ---- minority-carrier recovery network (pole gauge; C2 = measured C_ds
*      charge-master at Ki-A from data/{cds_file}) ----
.subckt DiodeRecov A K
B2 Ki Ai I=max(0,V(q_j)*(V(Ki)-V(Ai))/tau)
C1 q_j0 0 {{t_minor}} Rser=0
B1 0 q_j0 I=-I(R2)
D2 0 q_j0 ClampD
R1 N001 Ki {{Rs}}
R2 Ai A 1u
B3 N001 K V=if(r_max>0,-I(R2)*(r_max/(1+k_chg*V(q_j))+1u),0)
C2 Ki A {cds}
D1 Ai Ki MyDiode
E1 N002 0 q_j0 0 1
R3 q_j N002 1
C3 q_j 0 {{t_pole}}
.model ClampD D(Ron=1u,Roff=1,Vfwd=0)
.model MyDiode D(Is=Is,Rs=0,N=N)
.ends DiodeRecov
"""

# part -> (record, cds expression file, datasheet test conditions)
PARTS = {
    "ISC040N10NM8": (ISC040_RECOV, "ISC040N10NM8_cds_expr.txt", 50.0, 12.5,
                     "ISC040_RECOV"),
}


def _n(v: float) -> str:
    """SPICE engineering suffix for time-like values (s -> n)."""
    return f"{v * 1e9:.6g}n"


def build(rec: RecovRecord, cds_file: str, v_r: float, i_f: float,
          rec_name: str) -> str:
    cds = open(ROOT / "data" / cds_file, encoding="utf-8").read().strip()
    cds = "Q=" + cds.split("Q=", 1)[1]
    tau_s = f"{rec.tau:.6g}"
    pts = "".join(
        f"*   {d:>6g} A/us: Qrr {q:7.2f} nC ({(q / qt - 1) * 100:+.1f} %), "
        f"t_rr {t:6.2f} ns ({(t / tt - 1) * 100:+.1f} %)  [target {qt:g} nC / {tt:g} ns]\n"
        for (d, qt, tt), (_d, q, t) in zip(rec.targets, rec.achieved,
                                    strict=True)
    )
    header = HEADER.format(
        part=rec.part, rec_name=rec_name, cds_file=cds_file,
        v_r=f"{v_r:g}", i_f=f"{i_f:g}", tau=tau_s, tminor=_n(rec.t_minor),
        tpole=_n(rec.t_pole), points=pts.rstrip("\n").replace("*   ", "*   "),
        rms=f"{rec.rms_rel * 100:.2f}",
    )
    device = DEVICE.format(
        part=rec.part, sub=f"{rec.part.lower()}_caps", cds_file=cds_file,
        is_d=f"{rec.is_diode:g}", rs_d=f"{rec.rs_diode:g}", n_d=f"{rec.n_diode:g}",
        tau=tau_s, tminor=_n(rec.t_minor), tpole=_n(rec.t_pole),
        k_chg=f"{rec.k_chg:g}", r_max=f"{rec.r_max:g}", cds=cds,
    )
    return header + device


def main() -> None:
    out_dir = ROOT / "out"
    out_dir.mkdir(exist_ok=True)
    for part, (rec, cds_file, v_r, i_f, rec_name) in PARTS.items():
        path = out_dir / f"{part}_recov.subckt"
        path.write_text(build(rec, cds_file, v_r, i_f, rec_name), encoding="utf-8")
        print(f"{part}: {path}  tau={rec.tau:.6g} t_minor={_n(rec.t_minor)} "
              f"t_pole={_n(rec.t_pole)}  RMS {rec.rms_rel * 100:.2f} %")


if __name__ == "__main__":
    main()
