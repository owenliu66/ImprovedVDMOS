"""Fit the IMCQ120R004M2H (1200 V, 4 mOhm class, CoolSiC trench, Kelvin source)
static I-V at 25 C and 175 C and study the temperature dependence of the
improved-VDMOS channel parameters.

Protocol (rev. 2 -- user-directed: gate cap FREED, k_lambda FIXED at 0):

  free  = k_p, v_th0, v_sub, r_d, k_kneesharp, k_eta, v_dbsat,
          v_ovmax, k_ovsharp                                          (9 params)
  fixed = k_lambda = 0  -- the 0-20 V data carries no deep-saturation
                           information, and when freed k_lambda pinned at the
                           2e-3 1/V search guard in EVERY fit (sigma_rel 35/64):
                           it was a bound, not a measurement. Cost of fixing it:
                           +0.16 pp (25 C) / +0.06 pp (175 C) RMSE, and the
                           high-v_gs curves lose their output slope (residuals
                           on the v_gs = 15 curve drift -3.9 % @3.7 V ->
                           -11.4 % @11.5 V).
            r_s = 0     -- the device has a KELVIN source: the gate loop is not
                           degenerated by the source bond wire, so gate
                           degeneration is physically zero. r_d then absorbs the
                           whole terminal series path (package + source metal +
                           substrate + undepleted drift).
            k_theta = 0, v_vsat = 1e4, g_k = 0, v_kneemin default.
                           k_theta/v_vsat are not sensed (probe: k_theta -> 1e-4,
                           v_vsat -> 1e4 at identical RMSE).
  bounds: r_d <= datasheet Rds(on) chord at that temperature (3.7 mOhm @25 C,
          8.9 mOhm @175 C). Relaxing to 6 mOhm changes nothing -- the fit
          chooses 1.9 mOhm on its own.

CAP RESULT (rev. 2 headline): v_ovmax / k_ovsharp are NOT sensed on this device.
  Both fits run them to the identity limit (v_ovmax 22-67 V against a maximum
  sampled v_ov of 13.4 V; k_ovsharp 10-39 against the 40 bound), sigma_rel = inf,
  and the Jacobian goes rank-deficient (6/9 at 25 C, 7/9 at 175 C).
  dv_ov_eff/dv_ov = 1.00000 at every sampled gate bias -- the cap is inert. It
  CANNOT help because the model already sits BELOW the data at high v_gs
  (residuals -9 to -11 %) and the cap can only REDUCE current. The datasheet
  (Figure, p. 9) confirms the physics: the transfer characteristic at V_DS = 20 V
  is convex all the way to ~4200 A at V_GS = 20 V -- no charge saturation -- and
  the output curves do not plateau at a current limit, they EXIT the 1600 A plot
  frame. (Rev. 1 of the report called that a "pulsed-test current limit"; that
  was wrong and is corrected here against the datasheet figure.)

FIT-QUALITY LIMIT (rev. 2): the ~7-8.5 % floor is a MODEL-FORM limit, not a
  weighting/bound problem. The implied channel conductance at the near-origin
  ohmic points grows SUPER-linearly with overdrive: implied v_ov = 0.24, 0.72,
  2.09, 3.83, 6.99, 10.85 V at v_gs = 7, 8, 10, 12, 15, 18 -- dv_ov/dv_gs rises
  0.48 -> 1.29, i.e. exceeds 1. The model's channel conductance is locked to
  k_p*v_ov_eff with 0 <= dv_ov_eff/dv_ov <= 1, so it cannot produce that.
  Measured consequences: v_sub lands at 0.83-0.99 V (near the 1.0 bound) whether
  or not the 58.3 mA Vth anchor is in the set -- dropping the anchor and forcing
  v_sub <= 0.35 makes RMSE WORSE (8.53 -> 10.43 %) -- and the near-origin points
  of the v_gs = 8/10/12 curves carry +18 to +38 % residuals. See
  scripts/fit_imcq120_gain_probe.py: a trap-filling gain
  v_ov_eff = v_ov*(1 + k_beta*v_ov) -- the INVERSE of the charge cap -- halves
  the error (8.53 -> 4.61 %, 6.13 -> 3.31 %) and pins the Ron chords to 0.03 %.

Key findings (see out/IMCQ120_TEMPERATURE_REPORT.md):
  * fitted v_th0 (6.61/5.65 V) is NOT the datasheet Vth (4.20/3.20 V): constant
    +2.4 V offset (SiC current-dependent apparent threshold bridged by the
    softplus), but the SLOPE matches: -6.42 vs -6.67 mV/K.
  * v_sub ~ 0.836 -> 0.839 V: temperature-INVARIANT -> a shape knob here, not a
    thermal voltage (a real swing would rise ~50 % 298 -> 448 K).
  * k_p TC is entangled with r_d (corr +0.82..+0.88): +8.5 % with r_d free
    (beta = -0.20) vs -65 % with r_d fixed at the 25 C value (beta = +2.54,
    RMSE 17.6 %). The series/channel TC split is NOT identifiable from IV alone.
  * r_d: 1.89 -> 7.25 mOhm (x3.8): the whole Ron(T) TC lives here (the 1200 V
    drift region dominates). LINEAR r_d(T) goes NEGATIVE below -26 C -- use a
    power law (T/298K)^3.3 or an exponential.
  * Two-temperature parameter interpolation predicts the digitized Rds(on)-Tj
    curve within 1 % over 25..195 C, but -15 % at -46 C: TC extrapolation
    outside the fit window fails at low T.
  * Independent spec check never used in the fit: g_fs = 122 S at I_D = 185.2 A,
    V_DS = 20 V (datasheet Table 4) -- the fit gives 128.5 S (+5.4 %).

    python scripts/fit_imcq120_temperature.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy.optimize import brentq  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from vdmos_fit import CurveSet, Params, fit, vdmos_id  # noqa: E402
from vdmos_fit.fit import FitResult, identifiability  # noqa: E402

OUT = ROOT / "out"
T0, T1 = 298.15, 448.15  # fit temperatures, K

FREE = ("k_p", "v_th0", "v_sub", "r_d", "k_kneesharp", "k_eta", "v_dbsat",
        "v_ovmax", "k_ovsharp")

BASE25 = Params(k_p=150.0, v_th0=4.2, v_sub=0.08, v_ovmax=4.0, k_ovsharp=10.0,
                k_theta=0.0, v_vsat=1e4, k_kneesharp=2.0, k_eta=0.01, k_lambda=0.0,
                g_k=0.0, v_thk=1.6, v_kovsoft=0.1, v_dbsat=1.0, r_d=0.0025, r_s=0.0)
BASE175 = BASE25.replace(v_th0=3.2, r_d=0.0045)

MULTI = [dict(k_p=150.0, k_kneesharp=2.0, v_ovmax=4.0, k_ovsharp=10.0, v_dbsat=1.0),
         dict(k_p=300.0, k_kneesharp=1.0, v_ovmax=2.5, k_ovsharp=20.0, v_dbsat=0.5),
         dict(k_p=80.0, k_kneesharp=4.0, v_ovmax=6.0, k_ovsharp=5.0, v_dbsat=2.0),
         dict(k_p=500.0, k_kneesharp=2.0, v_ovmax=1.8, k_ovsharp=15.0, v_dbsat=0.8),
         dict(k_p=60.0, k_kneesharp=0.5, v_ovmax=8.0, k_ovsharp=8.0, v_dbsat=3.0),
         dict(k_p=1000.0, k_kneesharp=1.5, v_ovmax=1.2, k_ovsharp=30.0, v_dbsat=0.3)]


def load_imcq(path: Path) -> CurveSet:
    """IMCQ digitizer export uses `index,V_ds,I_d,V_gs` (not the legacy vgs/vds/ids)."""
    with path.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    return CurveSet(np.array([float(r["V_gs"]) for r in rows]),
                    np.array([float(r["V_ds"]) for r in rows]),
                    np.array([float(r["I_d"]) for r in rows]),
                    label=path.stem)


def multi_fit(data: CurveSet, base: Params, rmax: float) -> FitResult:
    best = None
    for s in MULTI:
        res = fit(data, start=base.replace(**s), free=FREE, weight="relative",
                  max_nfev=8000,
                  bounds_overrides={"r_d": (0.0, rmax), "k_eta": (1e-5, 0.05)})
        print(f"   start k_p={s['k_p']:7.4g} k_ksh={s['k_kneesharp']:4.2g}"
              f" v_ovmax={s['v_ovmax']:5.3g} k_ovsh={s['k_ovsharp']:5.3g}"
              f" -> RMSE {res.rmse_rel * 100:5.2f} %"
              + ("" if res.success else " [stopped]"))
        if best is None or res.rmse_rel < best.rmse_rel:
            best = res
    return best


def model_ron(p: Params, vg: float, itest: float = 185.2) -> float:
    """Model Rds(on) chord at the datasheet test current (185.2 A)."""
    v = brentq(lambda v: float(vdmos_id(v, vg, p)) - itest, 1e-4, 10.0)
    return v / itest


def report(res: FitResult, data: CurveSet, vth_pt: float) -> None:
    p = res.params
    print(f"\n=== {data.label}: RMSE_rel = {res.rmse_rel * 100:.2f} % "
          f"({res.n_points} pts, {res.n_free} free, "
          f"{'converged' if res.success else 'STOPPED'}) ===")
    for n in FREE:
        print(f"   {n:<12s} = {getattr(p, n):.6g}")
    print("   on_bounds:", res.on_bounds())
    off = float(vdmos_id(vth_pt, vth_pt, p))
    print(f"   Vth spec point ({vth_pt} V, {vth_pt} V): model {off * 1e3:.2f} mA vs 58.3 mA")
    rel = (vdmos_id(data.v_ds, data.v_gs, p) - data.i_d) / data.i_d
    print("   per-curve RMSE %:", {vg: round(float(np.sqrt(np.mean(
        rel[np.isclose(data.v_gs, vg)] ** 2)) * 100), 2) for vg in data.v_gs_grid()})
    print("   signed residuals (%), fmt err% @ v_ds:")
    for vg in data.v_gs_grid():
        m = np.isclose(data.v_gs, vg)
        if m.sum() == 1:
            continue
        o = np.argsort(data.v_ds[m])
        print(f"     v_gs={vg:4g}: " + " ".join(
            f"{a:+6.1f}@{b:5.2f}" for a, b in zip(rel[m][o] * 100, data.v_ds[m][o],
                                                  strict=True)))
    print(identifiability(res, FREE).summary())


def cap_activity(p: Params) -> None:
    """Is the freed charge cap ever active over the sampled gate biases?"""
    print(f"   cap activity (v_ovmax={p.v_ovmax:.1f} V, k_ovsharp={p.k_ovsharp:.1f}):")
    f = lambda v: v / (1 + (v / p.v_ovmax) ** p.k_ovsharp) ** (1 / p.k_ovsharp)  # noqa: E731
    for vg in (10, 14, 18, 20):
        v_ov = p.v_sub * np.logaddexp(0.0, (vg - p.v_th0) / p.v_sub)
        der = (f(v_ov + 1e-6) - f(v_ov - 1e-6)) / 2e-6
        print(f"     v_gs={vg:2d}: v_ov={v_ov:6.3f} V  dv_ov_eff/dv_ov={der:.5f}")


def params_T(p25: Params, p175: Params, tc: float) -> Params:
    """Two-temperature parameter interpolation: linear in T except r_d, which
    must be a power law in absolute temperature (linear goes negative < -26 C)."""
    w = (tc - 25.0) / 150.0
    vals = {n: getattr(p25, n) + w * (getattr(p175, n) - getattr(p25, n))
            for n in FREE if n != "r_d"}
    gamma = np.log(p175.r_d / p25.r_d) / np.log(T1 / T0)
    vals["r_d"] = p25.r_d * ((tc + 273.15) / T0) ** gamma
    return p25.replace(**vals)


def plot_iv(d: CurveSet, p: Params, title: str, fname: str) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(13, 5.4))
    for vg in d.v_gs_grid():
        msk = np.isclose(d.v_gs, vg)
        if msk.sum() == 1:
            axes[0].plot(d.v_ds[msk], d.i_d[msk], "k*", ms=10)
            continue
        vd_data, id_data = d.v_ds[msk], d.i_d[msk]
        vd = np.linspace(0.0, vd_data.max(), 300)
        for ax in axes:
            ax.plot(vd_data, id_data, "o", ms=4, alpha=0.6,
                    label=f"v_gs={vg:g}" if ax is axes[0] else None)
            ax.plot(vd, vdmos_id(vd, vg, p), "--", alpha=0.85)
    axes[0].set_xlim(0, 21)
    axes[1].set_xlim(0, 3)
    axes[1].set_ylim(0, 120)
    for ax, t in zip(axes, [title, title + " (knee zoom)"], strict=True):
        ax.set_xlabel("v_ds [V]")
        ax.set_ylabel("i_d [A]")
        ax.set_title(t)
        ax.grid(alpha=0.3)
    axes[0].legend(fontsize=7, ncol=2, title="dots = data, dashed = fit")
    fig.savefig(OUT / fname, dpi=110, bbox_inches="tight")
    plt.close(fig)
    print("wrote", OUT / fname)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    d25 = load_imcq(ROOT / "data" / "IMCQ120R004M2H_IV_25C.csv")
    d175 = load_imcq(ROOT / "data" / "IMCQ120R004M2H_IV_175C.csv")

    print("=== 25 C multi-start (cap free, k_lambda = 0) ===")
    r25 = multi_fit(d25, BASE25, rmax=3.7e-3)
    print("=== 175 C multi-start (cap free, k_lambda = 0) ===")
    r175 = multi_fit(d175, BASE175, rmax=8.9e-3)
    p25, p175 = r25.params, r175.params

    report(r25, d25, 4.2)
    report(r175, d175, 3.2)

    # --- temperature comparison -------------------------------------------
    print("\n=== parameter drift 25 -> 175 C ===")
    for n in FREE:
        a, b = getattr(p25, n), getattr(p175, n)
        print(f"   {n:<12s} {a:10.5g} -> {b:10.5g}   ratio {b / a:6.3f}")
    print(f"   v_th0 slope = {(p175.v_th0 - p25.v_th0) / 150 * 1e3:.2f} mV/K"
          "   (datasheet Vth_Tj slope: -6.67 mV/K, offset +2.4 V constant)")
    beta = np.log(p175.k_p / p25.k_p) / np.log(T1 / T0)
    gamma = np.log(p175.r_d / p25.r_d) / np.log(T1 / T0)
    print(f"   k_p exponent beta (k_p ~ T^-beta) = {-beta:.2f}   [ENTANGLED with r_d]")
    print(f"   r_d exponent gamma (r_d ~ T^gamma) = {gamma:.2f}   ratio {p175.r_d / p25.r_d:.2f}")

    print("\n25 C fit:")
    cap_activity(p25)
    print("175 C fit:")
    cap_activity(p175)

    # probe: r_d fixed at the 25 C value -> k_p must carry the whole Ron TC
    best = None
    for s in MULTI:
        st = Params(**{**p175.as_dict(), **s, "r_d": p25.r_d})
        res = fit(d175, start=st, free=tuple(n for n in FREE if n != "r_d"),
                  weight="relative", max_nfev=8000,
                  bounds_overrides={"k_eta": (1e-5, 0.05)})
        if best is None or res.rmse_rel < best.rmse_rel:
            best = res
    bfix = np.log(best.params.k_p / p25.k_p) / np.log(T1 / T0)
    print(f"   probe (r_d fixed @25C value): RMSE {best.rmse_rel * 100:.2f} %"
          f"  k_p ratio {best.params.k_p / p25.k_p:.3f}  beta = {-bfix:.2f}")

    # independent spec check (never used in the fit)
    vg = brentq(lambda g: float(vdmos_id(20.0, g, p25)) - 185.2, 5.0, 18.0)
    h = 0.01
    gfs = (float(vdmos_id(20.0, vg + h, p25)) - float(vdmos_id(20.0, vg - h, p25))) / (2 * h)
    print(f"   g_fs @ I_D=185.2 A, V_DS=20 V: {gfs:.1f} S"
          f"   (datasheet Table 4 spec: 122 S, {(gfs - 122) / 122 * 100:+.1f} %)")

    # ZTC crossing
    vg_ztc = brentq(lambda vg: float(vdmos_id(19.5, vg, p25))
                    - float(vdmos_id(19.5, vg, p175)), 8.0, 19.0)
    print(f"   ZTC crossing (model, vds=19.5 V): v_gs = {vg_ztc:.2f} V"
          "   (datasheet transfer figure: ~14.2 V, ~1500 A)")

    # --- forward prediction vs digitized Rds(on)-Tj ------------------------
    rd_T = np.array([-45.73487367, -29.0419171, -14.83499841, 4.029034591, 32.06060317,
                     58.83232597, 89.06862466, 116.7852318, 144.5018389, 172.0327255,
                     195.525593])
    rd_18 = np.array([3.217735375, 3.228694746, 3.300057249, 3.469800929, 3.875297692,
                      4.434225661, 5.278097301, 6.242522033, 7.393256087, 8.716209049,
                      10.00158661]) * 1e-3
    r15_T = np.array([-46.04983511, -32.82536195, -18.93772927, -5.734770194,
                      15.99756949, 38.98975495, 70.58208207, 98.517468, 124.6592679,
                      155.8404509, 196.6002128])
    rd_15 = np.array([4.291753826, 4.264357083, 4.286346008, 4.357510057, 4.565738124,
                      4.905478655, 5.591580178, 6.406912612, 7.338459227, 8.664543233,
                      10.76563647]) * 1e-3
    e18 = [(model_ron(params_T(p25, p175, t), 18) - d) / d * 100
           for t, d in zip(rd_T, rd_18, strict=True)]
    e15 = [(model_ron(params_T(p25, p175, t), 15) - d) / d * 100
           for t, d in zip(r15_T, rd_15, strict=True)]
    print("\nRds(on)-Tj forward prediction (param interp, r_d power law):")
    print(f"   RMSE vgs=18 {np.sqrt(np.mean(np.square(e18))):.2f} %"
          f"   vgs=15 {np.sqrt(np.mean(np.square(e15))):.2f} %"
          f"   (25..195 C: within ~1 %; -46 C: ~-15 %)")

    # --- artifacts ----------------------------------------------------------
    plot_iv(d25, p25, "IMCQ120R004M2H output curves, 25 C", "imcq120_iv_25C_fit.png")
    plot_iv(d175, p175, "IMCQ120R004M2H output curves, 175 C", "imcq120_iv_175C_fit.png")

    fig, ax = plt.subplots(figsize=(8, 5.6))
    vgs = np.linspace(5, 20, 300)
    ax.plot(vgs, vdmos_id(19.5, vgs, p25), "-", label="model 25 C")
    ax.plot(vgs, vdmos_id(19.5, vgs, p175), "-", label="model 175 C")
    for d, c in ((d25, "C0"), (d175, "C1")):
        for vg in d.v_gs_grid():
            m = np.isclose(d.v_gs, vg) & (d.v_ds > 18.5)
            if np.any(m):
                ax.plot(vg, d.i_d[m].mean(), "o", color=c, ms=6)
    ax.axvline(vg_ztc, ls=":", color="gray")
    ax.annotate(f"ZTC v_gs = {vg_ztc:.1f} V", (vg_ztc, 1500), rotation=90, va="top", ha="right")
    ax.set_xlabel("v_gs [V]")
    ax.set_ylabel("i_d @ v_ds = 19.5 V [A]")
    ax.set_title("Transfer curves: 25 C vs 175 C (zero-temperature-coefficient crossing)")
    ax.grid(alpha=0.3)
    ax.legend()
    ax.set_yscale("log")
    fig.savefig(OUT / "imcq120_transfer_ztc.png", dpi=110, bbox_inches="tight")
    plt.close(fig)
    print("wrote", OUT / "imcq120_transfer_ztc.png")

    fig, ax = plt.subplots(figsize=(8, 5.6))
    ax.plot(rd_T, rd_18 * 1e3, "o", color="C1", label="digitized Rds(on) Vgs=18")
    ax.plot(r15_T, rd_15 * 1e3, "s", mfc="none", color="C2", label="digitized Rds(on) Vgs=15")
    Ts = np.linspace(-50, 200, 60)
    ax.plot(Ts, [model_ron(params_T(p25, p175, t), 18) * 1e3 for t in Ts], "-", color="C1",
            label=f"model pred (interp, r_d~T^{gamma:.2f})")
    ax.plot(Ts, [model_ron(params_T(p25, p175, t), 15) * 1e3 for t in Ts], "-", color="C2")
    ax.axvline(25, color="gray", ls=":")
    ax.axvline(175, color="gray", ls=":")
    ax.set_xlabel("T_j [degC]")
    ax.set_ylabel("Rds(on) chord @ 185.2 A [m$\\Omega$]")
    ax.set_title("Rds(on) vs T_j: two-temperature fit prediction vs digitized curve")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    fig.savefig(OUT / "imcq120_ron_Tj.png", dpi=110, bbox_inches="tight")
    plt.close(fig)
    print("wrote", OUT / "imcq120_ron_Tj.png")

    txt = OUT / "imcq120_fit_params.json"
    txt.write_text(json.dumps({"25C": p25.as_dict(), "175C": p175.as_dict(),
                               "rmse": {"25C": r25.rmse_rel, "175C": r175.rmse_rel},
                               "free": list(FREE)}, indent=2), encoding="utf-8")
    print("wrote", txt)


if __name__ == "__main__":
    main()
