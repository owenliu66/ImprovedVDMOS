# Honest placeholder when no diode data exists: generic Si body diode,
# loudly warned about -- never silently presented as fitted.
PLACEHOLDER_DIODE = Params(i_s=1e-9, k_n=1.0, i_sr=0.0, k_nr=2.0, i_kf=0.0,
                           r_diode=10e-3, a_rdiode=0.0, b_rdiode=0.0,
                           t_nom=25.0, k_xti=3.0, v_eg=1.1)


def merge_ivs(ivs: list[IVTable]) -> IVTable:
    if len(ivs) == 1:
        return ivs[0]
    return IVTable(
        np.concatenate([t.vgs for t in ivs]),
        np.concatenate([t.vds for t in ivs]),
        np.concatenate([t.ids for t in ivs]),
        np.concatenate([t.tj for t in ivs]),
        gate_known=any(t.gate_known for t in ivs),
        source="+".join(t.source for t in ivs),
        notes=(),
    )


def _qg_curve(qgs: list[QgTable]) -> QgCurveSet:
    q, v, i_d, v_ds = [], [], [], []
    for t in qgs:
        for qi, vi, cond in zip(t.qg, t.vgs, t.condition, strict=True):
            c = parse_condition(str(cond))
            q.append(qi)
            v.append(vi)
            i_d.append(abs(c.get("ids", 0.0)))
            v_ds.append(c.get("vds", 0.0))
    return QgCurveSet(np.array(q), np.array(v), np.array(i_d), np.array(v_ds))


@dataclass
class ReleaseResult:
    part: str
    preset: str
    ref_temp: float
    channel: dict = field(default_factory=dict)
    tc: dict = field(default_factory=dict)
    diode: dict = field(default_factory=dict)
    recov: dict = field(default_factory=dict)
    rmse: dict = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    files: list[str] = field(default_factory=list)
    meta: dict = field(default_factory=dict)


def _generic_header(part: str, res: ReleaseResult, variant: str,
                    extra: str = "") -> str:
    lines = [
        f"* {part} -- {variant} ImprovedVDMOS device subckt (4 terminals "
        "D G S K).",
        f"* GENERATED by the release pipeline (vdmos_fit.release) from a "
        f"{res.preset} preset fit at ref {res.ref_temp:g} C; records in "
        f"out/{part}_record.json. Never hand-edit.",
        f"* channel RMSE {res.rmse.get('channel_ref', float('nan'))*100:.2f}%"
        f" | TC RMSE {res.rmse.get('tc', float('nan'))*100:.2f}%"
        f" | diode RMSE "
        f"{(res.rmse.get('diode') or float('nan'))*100:.2f}%",
    ]
    lines += [f"* WARNING: {w}" for w in res.warnings]
    if extra:
        lines.append(extra)
    lines.append("* SOLVER: .options method=gear reltol=1e-4 recommended.")
    return "\n".join(lines) + "\n"


def build_part(csv_paths: list[str | Path], part: str,
               preset: str | Preset = "trench", ref_temp: float = 25.0,
               rdson_i_test: float | None = None,
               out_dir: str | Path = "out",
               with_recovery: bool = False, v_r: float = 50.0,
               multistart_limit: int | None = None,
               max_nfev: int = 8000) -> ReleaseResult:
    p = PRESETS[preset] if isinstance(preset, str) else preset
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    tables, report = load_tables(csv_paths, ref_temp)
    res = ReleaseResult(part=part, preset=p.name, ref_temp=ref_temp,
                        warnings=list(report))
    ivs = [t for t in tables if isinstance(t, IVTable)]
    if not ivs:
        raise IngestError(part, "-", "no IV (current-voltage) CSV found")
    rds = next((t for t in tables if isinstance(t, RdsSpec)), None)
    vth = next((t for t in tables if isinstance(t, VthSpec)), None)
    caps = [t for t in tables if isinstance(t, CapTable)]
    qgs = [t for t in tables if isinstance(t, QgTable)]
    rectbl = next((t for t in tables if isinstance(t, RecTable)), None)

    iv = merge_ivs(ivs)
    tq = third_quadrant_rows(iv)
    if tq is not None:
        res.warnings.append(
            f"{len(tq)} third-quadrant rows (gate ON, reverse) excluded "
            "from the diode fit; mirror-channel data validation pending")

    # ---- channel: ref-temp stage, then TC --------------------------------
    ch = fit_channel_ref(iv, rds, p, ref_temp=ref_temp,
                         rdson_i_test=rdson_i_test,
                         multistart_limit=multistart_limit, max_nfev=max_nfev)
    res.channel = ch.params.as_dict()
    res.rmse["channel_ref"] = ch.rmse_rel
    if not ch.success:
        res.warnings.append("channel ref fit hit max_nfev")
    if rds is not None or vth is not None:
        tcres = fit_channel_tc(ch.params, rds, vth, p,
                               rdson_i_test=rdson_i_test)
        res.tc = {k: tcres[k] for k in p.tc_free}
        res.rmse["tc"] = tcres["rmse_overall"]
    else:
        res.warnings.append("no Rds(on)/Vth specs: TC stage skipped "
                            "(subckt is ref-temp only)")

    # ---- diode ------------------------------------------------------------
    dio_res = fit_diode_stage(ivs, p)
    if dio_res is None:
        res.warnings.append("no body-diode data: PLAIN placeholder diode "
                            "card exported (NOT fitted)")
        dio = PLACEHOLDER_DIODE
    else:
        dio = dio_res.params
        res.diode = {k: getattr(dio, k) for k in
                     ("i_s", "k_n", "i_sr", "k_nr", "i_kf", "r_diode",
                      "a_rdiode", "b_rdiode", "v_eg", "k_xti", "t_nom")}
        res.rmse["diode"] = dio_res.rmse_rel

    # ---- caps -------------------------------------------------------------
    if not caps:
        raise IngestError(part, "-", "cap CSV (Ciss/Coss/Crss) required "
                                     "for the subckt export")
    model, cmax = caps_model_from_tables(caps, qgs,
                                         ch.params.r_d + ch.params.r_s)
    if cmax is not None:
        res.rmse["cmax"] = cmax

    # ---- recovery (opt-in; needs LTspice) ---------------------------------
    recov: RecovParams | None = None
    if with_recovery:
        if rectbl is None:
            raise IngestError(part, "-", "--recovery given but no REC CSV "
                                         "(Q_rr,t_rr,I_RM,I_sd,di/dt)")
        recov, rms, _ = recov_from_table(rectbl, part, dio, v_r=v_r)
        res.recov = {"tau": recov.tau, "t_minor": recov.t_minor,
                     "t_pole": recov.t_pole, "rms_rel": rms}
        res.warnings.append("recovery extracted from datasheet points "
                            "(LTspice grid)")

    # ---- export ------------------------------------------------------------
    res2, files = export_part(out, part, Params(**res.channel), dio, recov,
                              model, rmse=res.rmse, warnings=res.warnings,
                              preset=res.preset, ref_temp=ref_temp)
    res.warnings = res2.warnings
    res.files = files

    # ---- record + report ----------------------------------------------------
    import scipy
    res.meta = {"numpy": np.__version__, "scipy": scipy.__version__,
                "generated": time.strftime("%Y-%m-%d %H:%M:%S")}
    rec_path = out / f"{part}_record.json"
    rec_path.write_text(json.dumps(asdict(res), indent=1, default=str),
                        encoding="utf-8")
    res.files.append(str(rec_path))
    return res


def caps_model_from_tables(caps: list[CapTable], qgs: list[QgTable],
                           r_ds_on: float) -> tuple[CapModel, float | None]:
    """CapModel from ingested CAP tables, re-spliced at the Qg-extracted
    c_gdmax when QG tables exist. Returns (model, c_gdmax | None)."""
    ccs = CapCurveSet(
        np.concatenate([t.v for t in caps]),
        np.concatenate([t.c for t in caps]),
        np.concatenate([np.full(len(t.v), t.kind) for t in caps]),
        label="ingest",
    )
    model = build_cap_model(ccs)
    cmax = None
    if qgs:
        fits = list(extract_cmax(model, _qg_curve(qgs), r_ds_on=r_ds_on))
        good = [f for f in fits if getattr(f, "c_gdmax", None)]
        if good:
            cmax = float(np.median([f.c_gdmax for f in good]))
            model = CapModel(model.tables, model.anchor,
                             CapParams(c_gd0=model.params.c_gd0,
                                       s_gd0=model.params.s_gd0,
                                       c_gdmax=cmax))
    return model, cmax


def recov_spec_from_table(rectbl: RecTable, part: str, dio: Params,
                          v_r: float = 50.0):
    """REC table -> RecovSpec (pure, no LTspice). The datasheet's OWN
    forward current (the I_sd / I_F column) drives every bench -- one
    i_f per row, never a hardcoded 12.5 A. spec.i_f alone is row 0's
    value (reporting); i_f_points carries the per-row values when the
    table's rows differ."""
    from .extract_recov import RecovSpec
    pts = tuple((float(dt / 1e6), float(q * 1e9), float(t * 1e9))
                for dt, q, t in zip(rectbl.didt, rectbl.qrr, rectbl.trr,
                                    strict=True))
    i_f_row = tuple(float(abs(v)) for v in rectbl.i_f)
    return RecovSpec(
        part=part,
        i_f=i_f_row[0], v_r=v_r,
        points=pts,
        i_f_points=i_f_row if len(set(i_f_row)) > 1 else (),
        is_diode=dio.i_s, rs_diode=dio.r_diode, n_diode=dio.k_n,
        cds_expr_file=f"{part}_cds_expr.txt")


def recov_from_table(rectbl: RecTable, part: str, dio: Params,
                     v_r: float = 50.0, progress=None):
    """REC table -> RecovSpec -> extract_recov grid (runs LTspice; slow).
    progress(msg) is forwarded to extract() for live status.
    Returns (RecovParams, rms_rel [PERCENT] | None, report text)."""
    from .extract_recov import extract
    spec = recov_spec_from_table(rectbl, part, dio, v_r)
    params, rtext = extract(spec, progress=progress)
    rec = RecovParams(tau=params["tau"], t_minor=params["t_minor"],
                      t_pole=params["t_pole"])
    return rec, params.get("rms_rel"), rtext


def export_part(out_dir: str | Path, part: str, p25: Params, dio: Params,
                recov: RecovParams | None, caps_model: CapModel,
                n_sub: int = 12, rmse: dict | None = None,
                warnings: list[str] | None = None, preset: str = "trench",
                ref_temp: float = 25.0) -> tuple[ReleaseResult, list[str]]:
    """Caps subckt + Cds expression + FULL/FAST subckt from current
    records. Export rule (user): recovery -> FULL; no recovery -> FAST,
    plain diode, no tt. n_sub is the ramp-sum table resolution knob.
    Returns the result (warnings gain the FAST-rule note) + file list."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    res = ReleaseResult(part=part, preset=preset, ref_temp=ref_temp,
                        rmse=dict(rmse or {}), warnings=list(warnings or []))
    caps_path = write_cap_subckt(caps_model, out / f"{part}_caps.subckt",
                                 name=f"{part.lower()}_caps",
                                 cgs_cgd_only=True, n_sub=n_sub)
    caps_text = caps_path.read_text(encoding="utf-8")
    cds_q = "Q=" + _rampsum_expr(
        *cap_charge_tables(caps_model, n_sub=n_sub)["ds"])
    (Path("data") / f"{part}_cds_expr.txt").write_text(
        f"Cds D S {cds_q}\n", encoding="utf-8")
    files = [str(caps_path)]
    if recov is not None:
        text = build_full(part, p25, dio, recov, cds_q, caps_text,
                          _generic_header(part, res, "FULL"))
        name = f"{part}_full.subckt"
    else:
        res.warnings.append("no recovery data: FAST export, plain diode, "
                            "no tt (user rule 2026-11-08)")
        text = build_fast(part, p25, dio, f"Cds D S {cds_q}", caps_text,
                          _generic_header(part, res, "FAST"), tt=None)
        name = f"{part}_fast.subckt"
    sub = out / name
    sub.write_text(text, encoding="utf-8")
    files.append(str(sub))
    return res, files
