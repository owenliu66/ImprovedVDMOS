"""Release orchestrator (session 30, Phase C): CSVs -> fitted records ->
subckt, in one command.

    build_part(csv_paths, part="MYFET", preset="trench", ...)

Pipeline (the agreed protocol): ingest/validate -> channel @ ref temp ->
diode @ ref temp (gate-off reverse rows) -> TC (specs at other temps) ->
caps (+ c_gdmax from Qg) -> recovery ONLY when --recovery and a REC CSV
are given (drives LTspice grids via extract_recov) -> export.

Export rule (user, 2026-11-08): recovery extracted -> FULL subckt; no
recovery -> FAST subckt with a plain diode and NO tt. Outputs:
out/<PART>_full|fast.subckt, out/<PART>_caps.subckt,
data/<PART>_cds_expr.txt, out/<PART>_record.json (+ report lines).
"""

